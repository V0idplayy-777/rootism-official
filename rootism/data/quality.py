"""
Automated Multi-Stage Dataset Quality & Security Sanitizer (Step 41).

Detects and rejects:
1. Corrupted / NUL-byte binary payloads and invalid Unicode surrogate codepoints.
2. Empty or trivially short files.
3. Minified / obfuscated / base64 / hex-dump files via max-line and mean-line length bounds.
4. Auto-generated machine spam (protobuf, thrift, lockfiles, compiler dumps).
5. Low-entropy repetitive spam (character Shannon entropy & duplicate-line fraction).
6. Placeholder-only stub files (`TODO`, `pass`, `NotImplementedError` without real logic).
7. Syntax-broken code when strict syntax validation is requested.
8. Security hazards: CVE-2021-42574 Trojan Source Unicode bidirectional overrides,
   embedded prompt-injection attacks (`ignore previous instructions`, spoofed Rootism control tags),
   fork bombs, and embedded private credentials/keys.
"""

from __future__ import annotations

import math
import re
from collections import Counter
from dataclasses import asdict, dataclass
from typing import Any

from rootism.languages.registry import validate_code_syntax

# CVE-2021-42574 Trojan Source bidirectional control codepoints
_BIDI_TROJAN_CODEPOINTS: frozenset[str] = frozenset(
    {
        "\u202a",  # LRE
        "\u202b",  # RLE
        "\u202c",  # PDF
        "\u202d",  # LRO
        "\u202e",  # RLO
        "\u2066",  # LRI
        "\u2067",  # RLI
        "\u2068",  # FSI
        "\u2069",  # PDI
    }
)

_PROMPT_INJECTION_AND_MALICIOUS_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    (
        "CORPUS_PROMPT_INJECTION",
        re.compile(
            r"(?:ignore|disregard|override)\s+(?:all\s+)?(?:previous|prior|above|system)\s+(?:instructions|directives|prompts)",
            re.IGNORECASE,
        ),
    ),
    (
        "SPOOFED_ROOTISM_CONTROL_TOKEN",
        re.compile(r"<\|(?:system_start|tool_call_start|agent_confirm_res)\|>", re.IGNORECASE),
    ),
    (
        "SHELL_FORK_BOMB",
        re.compile(r":\(\)\s*\{\s*:\s*\|\s*:\s*&\s*\}\s*;\s*:"),
    ),
    (
        "LEAKED_PRIVATE_KEY",
        re.compile(r"-----BEGIN\s+(?:RSA\s+|EC\s+|OPENSSH\s+|DSA\s+)?PRIVATE\s+KEY-----"),
    ),
    (
        "LEAKED_AWS_KEY",
        re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    ),
)

_AUTOGENERATED_MARKERS: tuple[str, ...] = (
    "do not edit! generated by",
    "code generated by protoc-gen",
    "autogenerated by thrift",
    "this file was automatically generated",
    "@generated by",
)


def shannon_char_entropy(text: str) -> float:
    """Compute Shannon character entropy in bits per character."""
    if not text:
        return 0.0
    counts = Counter(text)
    n = float(len(text))
    return -sum((c / n) * math.log2(c / n) for c in counts.values())


@dataclass(frozen=True)
class QualityAssessment:
    passed: bool
    rejection_code: str | None
    detail: str | None
    char_length: int
    line_count: int
    mean_line_length: float
    max_line_length: int
    shannon_entropy_bits: float
    unique_line_ratio: float

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class DataQualityPipeline:
    """Configurable automated quality & security gate for code and natural-language corpora."""

    def __init__(
        self,
        *,
        min_chars: int = 32,
        max_chars: int = 1_000_000,
        max_single_line_chars: int = 1_200,
        max_mean_line_chars: float = 160.0,
        min_shannon_entropy_bits: float = 2.6,
        min_unique_line_ratio: float = 0.25,
        verify_code_syntax: bool = False,
    ) -> None:
        self.min_chars = min_chars
        self.max_chars = max_chars
        self.max_single_line_chars = max_single_line_chars
        self.max_mean_line_chars = max_mean_line_chars
        self.min_shannon_entropy_bits = min_shannon_entropy_bits
        self.min_unique_line_ratio = min_unique_line_ratio
        self.verify_code_syntax = verify_code_syntax

    def evaluate(
        self,
        raw_content: str | bytes,
        *,
        modality: str = "source_code_curated",
        language: str | None = None,
    ) -> QualityAssessment:
        if isinstance(raw_content, bytes):
            if b"\x00" in raw_content:
                return QualityAssessment(False, "BINARY_NUL_BYTES", "Contains NUL binary bytes", 0, 0, 0.0, 0, 0.0, 0.0)
            try:
                text = raw_content.decode("utf-8", errors="strict")
            except UnicodeDecodeError as exc:
                return QualityAssessment(False, "INVALID_UTF8_ENCODING", str(exc), 0, 0, 0.0, 0, 0.0, 0.0)
        else:
            text = raw_content
            if "\x00" in text:
                return QualityAssessment(False, "BINARY_NUL_BYTES", "Contains NUL character", 0, 0, 0.0, 0, 0.0, 0.0)
            try:
                text.encode("utf-8", errors="strict")
            except UnicodeEncodeError as exc:
                return QualityAssessment(False, "INVALID_UNICODE_SURROGATE", str(exc), 0, 0, 0.0, 0, 0.0, 0.0)

        stripped = text.strip()
        char_len = len(text)
        if not stripped or len(stripped) < self.min_chars:
            return QualityAssessment(
                False,
                "EMPTY_OR_TOO_SHORT",
                f"Trimmed length {len(stripped)} < min_chars {self.min_chars}",
                char_len,
                0,
                0.0,
                0,
                0.0,
                0.0,
            )
        if char_len > self.max_chars:
            return QualityAssessment(
                False,
                "EXCESSIVE_DOCUMENT_SIZE",
                f"Length {char_len} > max_chars {self.max_chars}",
                char_len,
                0,
                0.0,
                0,
                0.0,
                0.0,
            )

        lines = text.splitlines()
        line_count = max(1, len(lines))
        max_line = max((len(ln) for ln in lines), default=0)
        mean_line = char_len / float(line_count)
        non_empty_lines = [ln.strip() for ln in lines if ln.strip()]
        unique_ratio = (
            len(set(non_empty_lines)) / float(len(non_empty_lines))
            if non_empty_lines
            else 0.0
        )
        entropy = shannon_char_entropy(text[:16384])

        # Security & Trojan Source checks first
        if any(ch in _BIDI_TROJAN_CODEPOINTS for ch in text):
            return QualityAssessment(
                False,
                "TROJAN_SOURCE_BIDI_UNICODE",
                "Detected bidirectional Unicode control codepoint (CVE-2021-42574).",
                char_len,
                line_count,
                round(mean_line, 2),
                max_line,
                round(entropy, 4),
                round(unique_ratio, 4),
            )

        for code, pattern in _PROMPT_INJECTION_AND_MALICIOUS_PATTERNS:
            if pattern.search(text):
                return QualityAssessment(
                    False,
                    code,
                    f"Matched security/injection filter: {code}",
                    char_len,
                    line_count,
                    round(mean_line, 2),
                    max_line,
                    round(entropy, 4),
                    round(unique_ratio, 4),
                )

        # Minified / giant-blob check
        if max_line > self.max_single_line_chars or mean_line > self.max_mean_line_chars:
            return QualityAssessment(
                False,
                "MINIFIED_OR_BLOB_LINE_LENGTH",
                f"max_line={max_line}, mean_line={mean_line:.1f} exceed bounds",
                char_len,
                line_count,
                round(mean_line, 2),
                max_line,
                round(entropy, 4),
                round(unique_ratio, 4),
            )

        # Autogenerated spam header check
        header_lower = "\n".join(lines[:10]).lower()
        for marker in _AUTOGENERATED_MARKERS:
            if marker in header_lower:
                return QualityAssessment(
                    False,
                    "AUTOGENERATED_SPAM",
                    f"Matched autogenerated marker: {marker!r}",
                    char_len,
                    line_count,
                    round(mean_line, 2),
                    max_line,
                    round(entropy, 4),
                    round(unique_ratio, 4),
                )

        # Repetition / low-entropy spam check
        if entropy < self.min_shannon_entropy_bits:
            return QualityAssessment(
                False,
                "LOW_SHANNON_ENTROPY_SPAM",
                f"Shannon entropy {entropy:.2f} bits < {self.min_shannon_entropy_bits}",
                char_len,
                line_count,
                round(mean_line, 2),
                max_line,
                round(entropy, 4),
                round(unique_ratio, 4),
            )

        if len(non_empty_lines) >= 8 and unique_ratio < self.min_unique_line_ratio:
            return QualityAssessment(
                False,
                "REPEATED_LINE_SPAM",
                f"Unique non-empty line ratio {unique_ratio:.2f} < {self.min_unique_line_ratio}",
                char_len,
                line_count,
                round(mean_line, 2),
                max_line,
                round(entropy, 4),
                round(unique_ratio, 4),
            )

        # Stub-only code check
        if modality.startswith("source_code") and len(non_empty_lines) <= 4:
            joined_lower = " ".join(non_empty_lines).lower()
            if ("todo" in joined_lower or "notimplementederror" in joined_lower) and "return " not in joined_lower:
                return QualityAssessment(
                    False,
                    "STUB_ONLY_CODE",
                    "Placeholder TODO / NotImplementedError stub with no substantive implementation.",
                    char_len,
                    line_count,
                    round(mean_line, 2),
                    max_line,
                    round(entropy, 4),
                    round(unique_ratio, 4),
                )

        if self.verify_code_syntax and language is not None and modality.startswith("source_code"):
            syn = validate_code_syntax(language, text)
            if not syn.valid:
                return QualityAssessment(
                    False,
                    "MALFORMED_CODE_SYNTAX",
                    f"{syn.validator_used}: {syn.error_message}",
                    char_len,
                    line_count,
                    round(mean_line, 2),
                    max_line,
                    round(entropy, 4),
                    round(unique_ratio, 4),
                )

        return QualityAssessment(
            passed=True,
            rejection_code=None,
            detail=None,
            char_length=char_len,
            line_count=line_count,
            mean_line_length=round(mean_line, 2),
            max_line_length=max_line,
            shannon_entropy_bits=round(entropy, 4),
            unique_line_ratio=round(unique_ratio, 4),
        )
